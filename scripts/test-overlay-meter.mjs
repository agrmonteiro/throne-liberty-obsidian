import assert from 'node:assert/strict'
import fs from 'node:fs'
import ts from 'typescript'

const input = fs.readFileSync(new URL('../src/engine/overlayMeter.ts', import.meta.url), 'utf8')
const code = ts.transpileModule(input, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText
const { OverlayMeter, METER_IDLE_MS, overlaySourceWarning, resolveOverlayNames } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)
const meter = new OverlayMeter(7, { 10: 'Garra', 11: 'Garra' })
const event = (ms, damage = 100, sourceId = 7, skillId = 10) => ({ time: ms / 1000, damage, sourceId, skillId, criticalCandidate: true, heavyCandidate: 1 })
assert.equal(meter.add(event(1000, 999, 8)), false, 'Outro personagem deve ser ignorado')
assert.equal(meter.snapshot(1000).startedAt, null)
meter.add(event(1000))
meter.add(event(2000, 200, 7, 11))
let state = meter.snapshot(11000)
assert.equal(state.total, 300)
assert.equal(state.dps, 30, 'DPS deve incluir pausa desde o primeiro dano')
assert.equal(state.skills.length, 1, 'Variações da mesma habilidade devem ser agrupadas')
assert.equal(state.skills[0].hits, 2)
assert.equal(state.skills[0].critical, 2)
assert.equal(state.skills[0].heavy, 2)
assert.equal(meter.snapshot(2000 + METER_IDLE_MS).waitingReset, true)
assert.equal(meter.snapshot(2000 + METER_IDLE_MS).total, 300, 'O acumulado fica visível até o próximo dano')
assert.equal(meter.add(event(2000 + METER_IDLE_MS, 500, 8)), false)
assert.equal(meter.snapshot(2000 + METER_IDLE_MS).total, 300, 'Dano de outro não reinicia sessão')
meter.add(event(2000 + METER_IDLE_MS, 500))
state = meter.snapshot(2000 + METER_IDLE_MS)
assert.equal(state.total, 500, 'Exatamente 5 minutos devem iniciar nova sessão')
assert.equal(state.hits, 1)
meter.reset(400000)
assert.equal(meter.snapshot(400001).total, 0)
assert.equal(meter.snapshot(400001).skills.length, 0, 'Reset deve limpar o detalhamento também')
assert.equal(meter.add(event(399999)), false, 'Evento atrasado anterior ao reset não pode repovoar a sessão')
meter.add(event(400100))
meter.add(event(400100 + METER_IDLE_MS - 1))
assert.equal(meter.snapshot(700100).total, 200, 'Antes dos 5 minutos deve continuar acumulando')
meter.selectSource(8)
assert.equal(meter.snapshot().total, 0)
assert.equal(meter.add(event(900000)), false)
assert.equal(meter.add(event(900000, 100, 8)), true)
console.log('OK: origem, agrupamento, DPS com pausas, limite de 5 min, reset conjunto e eventos atrasados.')

const stacked = new OverlayMeter(7, { 10: 'Garra' })
for (const [index, [damage, criticalCandidate, heavyCandidate]] of [[10, false, 0], [20, true, 0], [30, false, 1], [40, true, 1]].entries()) {
  stacked.add({ ...event(1000 + index * 1000), damage, criticalCandidate, heavyCandidate })
}
const chart = stacked.snapshot(5000)
assert.deepEqual(chart.damageByKind, { normal: 10, critical: 20, heavy: 30, criticalHeavy: 40 })
assert.equal(Object.values(chart.damageByKind).reduce((a, b) => a + b, 0), chart.total)
assert.deepEqual(chart.skills[0].damageByKind, chart.damageByKind)
assert.equal(chart.critical, 2)
assert.equal(chart.heavy, 2)
stacked.reset()
assert.deepEqual(stacked.snapshot().damageByKind, { normal: 0, critical: 0, heavy: 0, criticalHeavy: 0 })
console.log('OK: quatro faixas exclusivas somam o total, sem duplicar crítico pesado; reset limpa as faixas.')

const sourceState = { status: 'live', config: { sourceId: 7, autoSource: false }, sources: [{ id: 8, damage: 500 }] }
assert.match(overlaySourceWarning(sourceState), /outras origens/)
sourceState.config.sourceId = null
assert.match(overlaySourceWarning(sourceState), /Selecione sua origem/)
sourceState.config.sourceId = 8
assert.equal(overlaySourceWarning(sourceState), null)
sourceState.status = 'error'
assert.equal(overlaySourceWarning(sourceState), null, 'Aviso de origem não deve esconder erro da captura')
console.log('OK: origem ausente ou incorreta gera aviso; captura com erro mantém o erro visível.')

const automatic = new OverlayMeter()
automatic.reset(1000)
assert.equal(automatic.add(event(900, 100, 20)), false)
assert.equal(automatic.sourceId, null, 'Evento anterior ao reset não pode identificar origem')
assert.equal(automatic.add(event(1000, 0, 20)), false)
assert.equal(automatic.add(event(1000, 100, -1)), false)
assert.equal(automatic.sourceId, null)
assert.equal(automatic.add(event(1000, 100, 20)), false, 'Primeiro atacante não é evidência de identidade')
automatic.selectSource(20, 1000)
assert.equal(automatic.add(event(1000, 100, 20)), true)
assert.equal(automatic.sourceId, 20)
assert.equal(automatic.snapshot(1000).total, 100, 'Primeiro dano deve ser contado na identificação')
assert.equal(automatic.add(event(1100, 999, 30)), false)
assert.equal(automatic.sourceId, 20, 'Outra origem não deve roubar a seleção')
automatic.reset(1200)
assert.equal(automatic.sourceId, 20, 'Reset comum mantém a origem')
automatic.selectSource(null, 1300)
assert.equal(automatic.add(event(1400, 200, 30)), false, 'Redetectar não pode adivinhar a identidade pelo dano')
automatic.selectSource(30, 1300)
assert.equal(automatic.add(event(1400, 200, 30)), true)
assert.equal(automatic.sourceId, 30, 'Redetectar deve aceitar a próxima origem válida')
assert.equal(automatic.snapshot(1400).total, 200)
console.log('OK: identificação explícita, eventos inválidos e rejeição de primeiro atacante sem identidade.')

const rescan = new OverlayMeter(20)
rescan.add(event(1000, 100, 20))
assert.equal(rescan.add(event(2999, 999, 30)), false)
assert.equal(rescan.snapshot(9000).total, 100, 'Esperar redetecção não apaga o acumulado')
assert.equal(rescan.add(event(3000, 200, 30)), false)
assert.equal(rescan.sourceId, 20)
assert.equal(rescan.snapshot(3000).total, 100, 'Pausa não deve trocar de jogador')
assert.equal(rescan.snapshot(3000).hits, 1)
assert.equal(rescan.add(event(5000, 300, 20)), true)
assert.equal(rescan.snapshot(5000).total, 400, 'Mesma origem continua acumulando após pausa curta')
assert.equal(rescan.add(event(7000, 400, 40)), false, 'Origem manual não muda por inatividade')
assert.equal(rescan.add(event(5000 + METER_IDLE_MS, 999, 40)), false, 'Nem 5 min devem escolher outro jogador')
console.log('OK: origem fica fixa nas pausas, sem misturar jogadores.')

const renamedMeter = new OverlayMeter(7)
renamedMeter.add(event(1000, 100, 7, 100))
renamedMeter.add(event(2000, 200, 7, 101))
const beforeNames = { session: renamedMeter.snapshot(3000) }
const afterNames = resolveOverlayNames(beforeNames, { 100: 'Nome confirmado', 101: 'Nome confirmado' })
assert.equal(afterNames.session.total, beforeNames.session.total)
assert.equal(afterNames.session.skills.length, 1)
assert.equal(afterNames.session.skills[0].name, 'Nome confirmado')
assert.equal(afterNames.session.skills[0].damage, 300)
assert.equal(afterNames.session.skills[0].hits, 2)
assert.equal(beforeNames.session.skills.length, 2, 'Atualizar exibição não altera a sessão original')
assert.equal(resolveOverlayNames(beforeNames, {}).session.skills.length, 2)
console.log('OK: nomes atualizados no acumulado, variantes agrupadas e números preservados.')

const skillNames = JSON.parse(fs.readFileSync(new URL('../src/data/overlaySkillNames.json', import.meta.url), 'utf8'))
const variants = JSON.parse(fs.readFileSync(new URL('../src/data/overlaySkillVariants.json', import.meta.url), 'utf8'))
const judgment = new OverlayMeter(7)
judgment.add(event(1000, 100, 7, 968485880))
judgment.add(event(2000, 200, 7, 968448884))
const originalJudgment = { session: judgment.snapshot(3000) }
const resolvedJudgment = resolveOverlayNames(originalJudgment, skillNames)
assert.equal(resolvedJudgment.session.skills.length, 2, 'Especialização com ícone próprio deve ficar separada da base')
assert.equal(resolvedJudgment.session.skills[0].name, variants['968448884'].name)
assert.equal(resolvedJudgment.session.skills[1].name, 'Raio do Julgamento')
assert.equal(resolvedJudgment.session.total, originalJudgment.session.total)
assert.deepEqual(resolvedJudgment.session.damageByKind, originalJudgment.session.damageByKind)
assert.equal(resolvedJudgment.session.hits, originalJudgment.session.hits)
assert.equal(originalJudgment.session.skills[0].name, 'Habilidade 968448884')
console.log('OK: Uso consecutivo reconhecido, separado da base e acumulado preservado no reload.')
